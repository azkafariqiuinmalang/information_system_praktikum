import numpy as np

wj = np.array([30, 20, 20, 20, 10])
data = np.array([["kurang", "baik", "baik", 5000000, "rendah"],["baik", "sedang", "sedang",
4000000, "sedang"],["sedang", "sangat baik", "baik", 6500000, "tinggi"]])
xij = np.array([[2, 4, 4, 5000000, 1],[4, 3, 3, 4000000, 2],[3, 5, 4, 6500000, 3]])

wk = np.array([])
for k in range(5):
  wk = np.append(wk, wj[k]/sum(wj))

si = np.array([])
for i in range(3):
   s = 1
   for j in range(5):
      if j == 3 or j == 4:
        s = s*(np.pow(xij[i][j],(-wk[j])))
      else:
         s = s*(np.pow(xij[i][j],(wk[j])))
   si = np.append(si, s)

vi = np.array([])
for l in range(3):
      v = si[l]/sum(si)
      vi = np.append(vi, v)

